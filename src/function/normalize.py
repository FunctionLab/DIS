## Module
import os
import glob
import h5py
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from scipy.stats import t, mannwhitneyu


## This function loads DIS+ predictions from a '.h5' file, or from all '.h5' files in a directory
def load_prediction_data(pred_path, dataset_key = 'data'):
    ## 0. Input arguments
        # pred_path (str): path of DIS+ prediction '.h5' file, or directory containing DIS+ prediction '.h5' files
        # dataset_key (str): name of the data object in '.h5' file (Default: 'data')

    ## 1. Obtain the list of '.h5' files to be loaded
    if os.path.isfile(pred_path):
        pred_files = [pred_path]
    else:
        pred_files = sorted(glob.glob(os.path.join(pred_path, '*.h5')))
    if len(pred_files) == 0:
        raise FileNotFoundError('No .h5 files found in: ' + pred_path)

    ## 2. Read in the data object of each file, concatenate into one data frame (each row represents a variant, each column represents a disease node)
    pred_df_list = []
    for pf in pred_files:
        with h5py.File(pf, 'r') as pred_h5:
            if dataset_key not in pred_h5:
                raise KeyError("Data object '" + dataset_key + "' not found in " + pf + '. Available: ' + str(list(pred_h5.keys())))
            pred_df_list.append(pd.DataFrame(np.array(pred_h5[dataset_key])))
    pred_df = pd.concat(pred_df_list, ignore_index = True)

    return pred_df


## This function computes the normalization stats (mean and standard deviation of each disease node) from DIS+ predictions of neutral variants
def compute_norm_stats(neutral_df, eps = 1e-8):
    ## 0. Input arguments
        # neutral_df (data frame): DIS+ predictions of neutral variants (each row represents a variant, each column represents a disease node)
        # eps (float): value used to replace standard deviation of 0 (Default: 1e-8)

    ## 1. Compute mean and population standard deviation of each disease node, store in a data frame with columns 'feature', 'mean', 'std'
    stats_df = pd.DataFrame({'feature': neutral_df.columns,
        'mean': neutral_df.mean().values,
        'std': neutral_df.std(ddof = 0).replace(0, eps).values})

    return stats_df


## This function loads the normalization stats file generated by compute_norm_stats()
def load_norm_stats(stats_file):
    ## 0. Input arguments
        # stats_file (str): path of normalization stats '.csv' file with columns 'feature', 'mean', 'std'

    ## 1. Read in the normalization stats, check the required columns
    stats_df = pd.read_csv(stats_file)
    if not {'feature', 'mean', 'std'}.issubset(stats_df.columns):
        raise ValueError('Normalization stats file must have columns: feature, mean, std')

    return stats_df


## This function Z-normalizes DIS+ predictions using the normalization stats computed from neutral variants
def normalize_prediction_data(pred_df, stats_df, eps = 1e-8):
    ## 0. Input arguments
        # pred_df (data frame): DIS+ predictions to be normalized (each row represents a variant, each column represents a disease node)
        # stats_df (data frame): normalization stats of each disease node, with columns 'feature', 'mean', 'std'
        # eps (float): value used to replace standard deviation of 0 (Default: 1e-8)

    ## 1. Check that the normalization stats cover the same disease nodes as the predictions
    if set(pred_df.columns) != set(stats_df.feature.values):
        raise ValueError('Normalization stats have ' + str(stats_df.shape[0]) + ' disease nodes but predictions have ' + str(pred_df.shape[1]) + '. Check that the stats file matches the prediction method (Sei or Seqweaver).')

    ## 2. Z-normalize the predictions of each disease node: (prediction - neutral mean) / neutral std
    node_mean = pd.Series(stats_df['mean'].values, index = stats_df.feature.values).reindex(pred_df.columns)
    node_std = pd.Series(stats_df['std'].values, index = stats_df.feature.values).reindex(pred_df.columns).replace(0, eps)
    norm_df = (pred_df - node_mean) / node_std

    return norm_df


## This function computes the mean and 95% confidence interval (half-width) of normalized predictions of a disease node
def compute_mean_ci95(node_pred):
    ## 0. Input arguments
        # node_pred (pandas series): normalized DIS+ predictions of a disease node across variants

    ## 1. Compute mean, and half-width of 95% confidence interval based on t distribution
    node_pred = node_pred.dropna()
    n = len(node_pred)
    if n < 2:
        return (node_pred.mean() if n else np.nan), np.nan
    node_mean = node_pred.mean()
    node_err = t.ppf(0.975, df = n - 1) * node_pred.std(ddof = 1) / np.sqrt(n)

    return node_mean, node_err


## This function plots the mean and 95% confidence interval of normalized predictions of a disease node across variant groups
def plot_node_mean_ci95(group_norm_dict, node, plot_title, out_name, fig_size = (7, 4.5), marker_size = 10):
    ## 0. Input arguments
        # group_norm_dict (dictionary): normalized DIS+ predictions of each variant group (including neutral variants), keyed by group label
        # node (int): column index of the disease node to be plotted
        # plot_title (str): title of the plot
        # out_name (str): path of output '.png' file
        # fig_size (tuple): figure size (Default: (7, 4.5))
        # marker_size (int): marker size (Default: 10)

    ## 1. Compute mean and 95% confidence interval of each variant group
    labels, means, errs = [], [], []
    for label, group_norm_df in group_norm_dict.items():
        node_pred = group_norm_df[node].dropna()
        node_mean, node_err = compute_mean_ci95(node_pred)
        labels.append(label + ' (N=' + str(len(node_pred)) + ')')
        means.append(node_mean)
        errs.append(node_err)

    ## 2. Plot the results, write to output file
    fig, ax = plt.subplots(figsize = fig_size)
    ax.errorbar(labels, means, yerr = errs, fmt = 'o', capsize = 4, ecolor = 'black', markersize = marker_size)
    ax.set_ylabel('Normalized Prediction (mean ± CI95)')
    ax.set_title(plot_title)
    ax.spines['top'].set_visible(False)
    ax.spines['right'].set_visible(False)
    ax.tick_params(axis = 'x', rotation = 45)
    plt.setp(ax.get_xticklabels(), ha = 'right')
    plt.tight_layout()
    fig.savefig(out_name, dpi = 200, bbox_inches = 'tight')
    plt.close(fig)

    return 1

## Compare one case group against neutrals across all disease nodes, with BH FDR correction.
def compare_all_nodes(case_norm_df, neutral_norm_df):
    from statsmodels.stats.multitest import multipletests
    rows = []
    for node in case_norm_df.columns:
        case = case_norm_df[node].dropna()
        neutral = neutral_norm_df[node].dropna()
        p = mannwhitneyu(case, neutral, alternative = 'greater').pvalue if len(case) and len(neutral) else np.nan
        effect = float(case.median() - neutral.median()) if len(case) and len(neutral) else np.nan
        rows.append({'Node': node, 'N_case': len(case), 'N_neutral': len(neutral), 'Effect_MedianDiff': effect, 'P': p})
    result = pd.DataFrame(rows)
    result['FDR'] = np.nan
    valid = result['P'].notna()
    if valid.any():
        result.loc[valid, 'FDR'] = multipletests(result.loc[valid, 'P'], method = 'fdr_bh')[1]
    return result


## Save normalized predictions in the same HDF5 'data' format as the input.
def save_normalized_predictions(norm_df, out_file, dataset_key = 'data'):
    with h5py.File(out_file, 'w') as h5f:
        h5f.create_dataset(dataset_key, data = norm_df.to_numpy(), compression = 'gzip')

